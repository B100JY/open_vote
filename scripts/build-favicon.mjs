import sharp from "sharp";
import {readFile,writeFile} from "node:fs/promises";
const svg=await readFile("src/app/icon.svg");
const sizes=[16,32,48,64];
const pngs=await Promise.all(sizes.map(size=>sharp(svg).resize(size,size).png().toBuffer()));
const header=Buffer.alloc(6+16*sizes.length);header.writeUInt16LE(1,2);header.writeUInt16LE(sizes.length,4);
let offset=header.length;
pngs.forEach((png,i)=>{const at=6+16*i;header[at]=sizes[i];header[at+1]=sizes[i];header.writeUInt16LE(1,at+4);header.writeUInt16LE(32,at+6);header.writeUInt32LE(png.length,at+8);header.writeUInt32LE(offset,at+12);offset+=png.length;});
await writeFile("src/app/favicon.ico",Buffer.concat([header,...pngs]));
await sharp(svg).resize(180,180).png().toFile("public/apple-touch-icon.png");
console.log("모아이 favicon.ico·애플 아이콘 생성 완료");
