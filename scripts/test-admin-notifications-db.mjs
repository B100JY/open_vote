import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
export async function testAdminNotifications({sql,json,create,cast}) {
 sql(`create table app_open_vote.members(id uuid primary key default gen_random_uuid(),role text default 'pending'); alter table app_open_vote.members enable row level security;grant all on app_open_vote.members to service_role;
 insert into app_open_vote.members(role) values('pending'),('admin'),('suspended');`);
 const migration=await readFile('supabase/migrations/20261030142519_auto_creator_notifications.sql','utf8');sql(migration);sql(migration);
 const dispatch=await readFile('supabase/migrations/20261030143751_notification_dispatch_limit.sql','utf8');sql(dispatch);sql(dispatch);
 assert.equal(sql("select count(*) from app_open_vote.members where role='creator';"),'1');
 assert.equal(sql("select count(*) from app_open_vote.members where role in ('admin','suspended');"),'2');
 sql('insert into app_open_vote.members default values;');
 assert.equal(sql("select count(*) from app_open_vote.members where role='pending';"),'0');
 const e=await create(false,2);
 assert.equal(json(cast(e,e.voters[0],'e'.repeat(64),'f'.repeat(64))).success,true);
 assert.equal(json(cast(e,e.voters[0],'e'.repeat(64),'f'.repeat(64))).success,false);
 assert.equal(sql(`select count(*) from app_open_vote.admin_notifications where election_id='${e.id}' and kind='vote_cast';`),'1');
 assert.equal(sql(`select count(*) from information_schema.columns where table_schema='app_open_vote' and table_name='admin_notifications' and column_name in ('ballot_id','registry_id','receipt_hash','phone','email','selection','ip');`),'0');
 sql("begin;insert into app_open_vote.members default values;rollback;");
 assert.equal(sql("select count(*) from app_open_vote.admin_notifications where kind='signup';"),'1');
 const claimed=json("select json_agg(n) from app_open_vote.claim_admin_notifications() n;");
 assert.equal(claimed.length,3);
 assert.equal(sql("select count(*) from app_open_vote.claim_admin_notifications();"),'0');
 const item=claimed[0];
 sql(`select app_open_vote.finish_admin_notification('${item.id}',0,true,null);`);
 assert.equal(sql(`select state from app_open_vote.admin_notifications where id='${item.id}';`),'sending');
 sql(`select app_open_vote.finish_admin_notification('${item.id}',1,false,'secret URL must be discarded');`);
 assert.equal(sql(`select last_error from app_open_vote.admin_notifications where id='${item.id}';`),'DELIVERY_FAILED');
 sql(`update app_open_vote.admin_notifications set next_attempt_at=now()-interval '1 minute',lease_until=now()-interval '1 minute';`);
 sql(`update app_open_vote.notification_dispatch_lock set lease_until=now()-interval '1 minute';`);
 assert.equal(sql("select count(*) from app_open_vote.claim_admin_notifications();"),'3');
 sql(`select app_open_vote.finish_admin_notification('${item.id}',2,true,null);`);
 assert.equal(sql(`select state from app_open_vote.admin_notifications where id='${item.id}';`),'sent');
 sql("update app_open_vote.notification_settings set vote_enabled=false;select count(*) from app_open_vote.claim_admin_notifications();");
 assert.equal(sql("select state from app_open_vote.admin_notifications where kind='vote_cast';"),'skipped');
 assert.equal(json(cast(e,e.voters[1],'a'.repeat(64),'b'.repeat(64))).success,true);
 assert.equal(sql("select count(*) from app_open_vote.admin_notifications where kind='vote_cast' and state='skipped';"),'2');
 sql("update app_open_vote.notification_settings set enabled=false;select count(*) from app_open_vote.claim_admin_notifications();");
 assert.equal(sql("select count(*) from app_open_vote.admin_notifications where state in ('pending','sending','failed');"),'0');
 assert.equal(sql("select count(*) from app_open_vote.permission_baseline_violations();"),'0');
 console.log('PASS auto creator / admin+suspended preserved / insert-only outbox / rollback / retry+lease / safe errors / settings / permissions');
}
